import { test, describe } from 'node:test';
import assert from 'node:assert';
import { PDFDocument } from 'pdf-lib';
import { createPdfBuffer, exportPdfWithStats } from '../server/services/pdfExportService.js';

describe('Server PDF Renderer Metadata & Provenance Tests', () => {
  const sampleMarkdown = `
# Module 5: Discrete Mathematics

## 1. Graph Theory
A graph $G = (V, E)$ consists of vertices $V$ and edges $E$.

| Vertex | Degree |
|---|---|
| A | 2 |
| B | 3 |
`;

  test('PDF is generated by TypedDoc server renderer with valid metadata', async () => {
    const pdfBuffer = await createPdfBuffer('Test Document', sampleMarkdown);
    assert.ok(Buffer.isBuffer(pdfBuffer));
    assert.ok(pdfBuffer.length > 0);

    const pdfDoc = await PDFDocument.load(pdfBuffer, { updateMetadata: false });

    // Verify creator and producer strictly identify the TypedDoc server engine
    assert.strictEqual(pdfDoc.getCreator(), 'TypedDoc Server PDF Engine');
    assert.strictEqual(pdfDoc.getProducer(), 'TypedDoc PDF Renderer');
    assert.strictEqual(pdfDoc.getTitle(), 'Test Document');
    assert.strictEqual(pdfDoc.getAuthor(), 'TypedDoc');
    assert.ok(pdfDoc.getCreationDate() instanceof Date);
  });

  test('No browser metadata appears in server-generated output', async () => {
    const pdfBuffer = await createPdfBuffer('Test Document', sampleMarkdown);
    const pdfDoc = await PDFDocument.load(pdfBuffer, { updateMetadata: false });

    const creator = pdfDoc.getCreator() || '';
    const producer = pdfDoc.getProducer() || '';

    // Verify browser engines (Chrome, Edge, Mozilla) are not present
    assert.strictEqual(creator.includes('Chrome'), false);
    assert.strictEqual(creator.includes('Mozilla'), false);
    assert.strictEqual(creator.includes('Edge'), false);
    assert.strictEqual(producer.includes('Chrome'), false);
    assert.strictEqual(producer.includes('Mozilla'), false);
  });

  test('records telemetry on buffer and exportPdfWithStats', async () => {
    const stats = await exportPdfWithStats('Test Telemetry', sampleMarkdown, {
      pageMode: 'clean-reflow',
      sourcePageCount: 3
    });

    assert.strictEqual(stats.pdfSource, 'server-pdf');
    assert.strictEqual(stats.renderer, 'pdf-lib');
    assert.strictEqual(stats.pageMode, 'clean-reflow');
    assert.strictEqual(stats.sourcePageCount, 3);
    assert.ok(typeof stats.pageCount === 'number');
    assert.ok(typeof stats.expansionRatio === 'number');

    // Also verified on raw buffer
    assert.strictEqual(stats.buffer.pdfSource, 'server-pdf');
    assert.strictEqual(stats.buffer.renderer, 'pdf-lib');
  });

  test('generates layout-specific provenance footers for clean-reflow and faithful', async () => {
    const reflowBuffer = await createPdfBuffer('Reflow Doc', sampleMarkdown, { pageMode: 'clean-reflow' });
    assert.strictEqual(reflowBuffer.pageMode, 'clean-reflow');

    const faithfulBuffer = await createPdfBuffer('Faithful Doc', sampleMarkdown, { pageMode: 'faithful' });
    assert.strictEqual(faithfulBuffer.pageMode, 'faithful');
  });
});
